"""查询清洗：剥掉考据/翻译题的提问套话，保留语义内核用于检索。

只作用于检索路径（向量 + BM25 共用），生成仍用原始 query。
举例：
    吾日三省吾身是谁说的，出自哪一篇  → 吾日三省吾身
    请将"上善若水"翻译成现代汉语       → 上善若水
"""

from __future__ import annotations

# 逐条替换（先长后短，避免半截匹配），全部按字面替换为空
_PHRASES = [
    "翻译成现代汉语", "翻译成现代文", "翻译成现代白话文", "并说明其比喻意义",
    "并说明其哲学内涵", "并说明韩非子的法治思想", "并说明庄子的辩论逻辑",
    "并解释其含义", "并解释", "并阐述老子思想", "并说明", "并讲述", "并翻译",
    "的出处是", "的出处", "出自《", "》中", "中哪一篇", "中哪一章",
    "出自哪一篇", "出自哪一章", "出自哪里", "出现在哪一篇",
    "是哪位思想家", "是谁说的", "是谁", "谁说的", "谁", "哪一篇", "哪一章",
    "请将", "请翻译", "请解释", "请", "翻译为", "翻译", "解释一下", "解释",
    "出自", "出处", "核心出处", "出处是", "核心", "思想源头", "最早", "可追溯到",
    "的故事", "在《", "中出现的",
]

def clean_query(query: str) -> str:
    """返回清洗后的检索用查询。已去重、去空白。"""
    cleaned = query
    for p in _PHRASES:
        cleaned = cleaned.replace(p, "")
    # 剥掉残留标点、引号与书名号（书名汉字保留，如 庄子》→庄子），只留语义内核
    for ch in ["《", "》", " ", "，", ",", "。", "？", "?", "！", "!", "？。",
               '"', '"', "‘", "’", "「", "」"]:
        cleaned = cleaned.replace(ch, "")
    return cleaned or query  # 清洗后为空则回退原始 query
