"""先贤人设注册表：4 位先贤的配置（id/name/books/persona_prompt/stance_hint）。

S4 辩论图的核心：每位先贤 = 人设 prompt + RAG 子图（book_id 限定检索范围）。
论点可回溯原著——子图只检索该先贤本人的著作。
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class SagePersona:
    """一位先贤的人设配置。"""
    id: str
    name: str
    dynasty: str
    school: str
    books: list[str]          # 语料库 book_id，RAG 子图检索范围
    persona_prompt: str       # 人设 system prompt（学派立场、语言风格、必引己著）
    stance_hint: str          # 立场摘要，用于紧急度话题相关度计算（embedding cos）

    @property
    def book_ids_str(self) -> str:
        return "、".join(self.books)


